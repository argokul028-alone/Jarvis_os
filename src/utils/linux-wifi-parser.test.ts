import test from 'node:test';
import assert from 'node:assert/strict';
import {
  classifyWifiBandFromFreq,
  dbmToSignalPercent,
  parseIpRouteDefaultGateway,
  parseIwScanOutput,
  parseNmcliWifiList,
  parseResolvConfDns,
  splitNmcliTerseLine,
} from './linux-wifi-parser.ts';

test('splitNmcliTerseLine preserves escaped colons inside BSSID and SSID values', () => {
  const line = '*:Office\\:5G:AA\\:BB\\:CC\\:DD\\:EE\\:FF:88:5180 MHz:WPA2 WPA3:866 Mbit/s:wlp2s0';
  assert.deepEqual(splitNmcliTerseLine(line), [
    '*',
    'Office:5G',
    'AA:BB:CC:DD:EE:FF',
    '88',
    '5180 MHz',
    'WPA2 WPA3',
    '866 Mbit/s',
    'wlp2s0',
  ]);
});

test('parseNmcliWifiList parses real nmcli output, deduplicates SSIDs, and tracks active network', () => {
  const sample = [
    ' :CafeGuest:11\\:22\\:33\\:44\\:55\\:66:44:2412 MHz:--:54 Mbit/s:wlp2s0',
    '*:HomeFiber_5G:AA\\:BB\\:CC\\:11\\:22\\:33:82:5240 MHz:WPA2:433 Mbit/s:wlp2s0',
    ' :HomeFiber_5G:AA\\:BB\\:CC\\:11\\:22\\:44:95:5240 MHz:WPA2:433 Mbit/s:wlp2s0',
    ' :NeighborNet:22\\:33\\:44\\:55\\:66\\:77:67:6115 MHz:SAE:1200 Mbit/s:wlp2s0',
    ' ::33\\:44\\:55\\:66\\:77\\:88:90:2437 MHz:WPA2:130 Mbit/s:wlp2s0',
  ].join('\n');

  const parsed = parseNmcliWifiList(sample, new Set(['HomeFiber_5G']), {
    iface: 'wlp2s0',
    ipAddress: '192.168.1.45',
    gateway: '192.168.1.1',
    dns: '1.1.1.1',
  });

  assert.equal(parsed.activeNetworkId, 'ssid:HomeFiber_5G');
  assert.equal(parsed.networks.length, 3);
  assert.equal(parsed.networks[0].ssid, 'HomeFiber_5G');
  assert.equal(parsed.networks[0].band, '5 GHz');
  assert.equal(parsed.networks[0].ipAddress, '192.168.1.45');
  assert.equal(parsed.networks[0].linkSpeedMbps, 433);
  assert.equal(parsed.networks[1].ssid, 'NeighborNet');
  assert.equal(parsed.networks[1].band, '6 GHz');
  assert.equal(parsed.networks[1].security, 'WPA3');
  assert.equal(parsed.networks[2].ssid, 'CafeGuest');
  assert.equal(parsed.networks[2].security, 'Open');
});

test('parseIwScanOutput parses iw dev scan blocks and converts dBm to percentage', () => {
  const sample = `
BSS aa:bb:cc:dd:ee:01(on wlan0)
\tfreq: 5180
\tsignal: -54.00 dBm
\tSSID: LabWiFi
\tRSN:\t * Version: 1
\t\t * Authentication suites: SAE
BSS aa:bb:cc:dd:ee:02(on wlan0)
\tfreq: 2437
\tsignal: -78.00 dBm
\tSSID: OpenHotspot
`;
  const parsed = parseIwScanOutput(sample, 'wlan0', 'LabWiFi');
  assert.equal(parsed.activeNetworkId, 'ssid:LabWiFi');
  assert.equal(parsed.networks.length, 2);
  assert.equal(parsed.networks[0].security, 'WPA3');
  assert.equal(parsed.networks[0].band, '5 GHz');
  assert.equal(parsed.networks[0].signalPercent, dbmToSignalPercent(-54));
  assert.equal(parsed.networks[1].security, 'Open');
  assert.equal(classifyWifiBandFromFreq(2437), '2.4 GHz');
});

test('parseIpRouteDefaultGateway and parseResolvConfDns parse real Linux route and DNS files', () => {
  const route = parseIpRouteDefaultGateway(
    'default via 192.168.1.1 dev wlp2s0 proto dhcp metric 600\n192.168.1.0/24 dev wlp2s0'
  );
  assert.deepEqual(route, { gateway: '192.168.1.1', iface: 'wlp2s0' });

  const dns = parseResolvConfDns('# Generated by NetworkManager\nnameserver 1.1.1.1\nnameserver 8.8.8.8\n');
  assert.deepEqual(dns, ['1.1.1.1', '8.8.8.8']);
});
